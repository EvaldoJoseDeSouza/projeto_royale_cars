    add column if not exists endereco text
        check (endereco is null or char_length(endereco) <= 200);

-- Quilometragem atual do veículo. Muda sozinha na devolução.
alter table veiculos
    add column if not exists quilometragem integer not null default 0
        check (quilometragem >= 0);

-- Locação: km de saída e de retorno, assinatura e taxas extras
alter table locacoes
    add column if not exists km_saida        integer check (km_saida >= 0),
    add column if not exists km_retorno      integer,
    add column if not exists assinatura_path text,          -- caminho do PNG no bucket "contratos"
    add column if not exists assinada_em     timestamptz,
    add column if not exists taxas_extras    numeric(10, 2) not null default 0 check (taxas_extras >= 0),
    add column if not exists taxas_motivo    text;

alter table locacoes drop constraint if exists km_retorno_valido;
alter table locacoes add constraint km_retorno_valido
    check (km_retorno is null or (km_saida is not null and km_retorno >= km_saida));

alter table locacoes drop constraint if exists taxas_com_motivo;
alter table locacoes add constraint taxas_com_motivo
    check (taxas_extras = 0 or char_length(trim(coalesce(taxas_motivo, ''))) >= 3);

-- Checklist de inspeção (null = item não conferido)
alter table manutencoes
    add column if not exists motor_ok  boolean,
    add column if not exists freios_ok boolean,
    add column if not exists pneus_ok  boolean,
    add column if not exists oleo_ok   boolean;


-- =====================================================================
-- 2. MODELOS DE PERMISSÃO
--    Um modelo só preenche as caixas de permissão na hora de cadastrar
--    ou editar alguém. Quem vale é sempre a permissão da pessoa
--    (tabela usuario_permissoes), igual nas 3 plataformas.
-- =====================================================================

create table if not exists modelos_permissao (
    id            bigint generated by default as identity primary key,
    nome          text not null unique check (char_length(trim(nome)) between 2 and 50),
    descricao     text check (descricao is null or char_length(descricao) <= 200),
    permissoes    text[] not null default '{}' check (permissoes <@ array[
        'clientes_ver', 'clientes_gerenciar', 'clientes_arquivar',
        'veiculos_ver', 'veiculos_gerenciar', 'veiculos_arquivar',
        'locacoes_ver', 'locacoes_gerenciar', 'locacoes_cancelar',
        'manutencoes', 'financeiro', 'relatorios', 'relatorios_financeiros']),
    criado_em     timestamptz not null default now(),
    atualizado_em timestamptz
);

alter table modelos_permissao enable row level security;

drop policy if exists modelos_ver on modelos_permissao;
drop policy if exists modelos_chefe on modelos_permissao;
create policy modelos_ver on modelos_permissao for select to authenticated
    using (usuario_ativo());
create policy modelos_chefe on modelos_permissao for all to authenticated
    using (eh_chefe()) with check (eh_chefe());

create or replace function tg_modelos()
returns trigger language plpgsql security definer set search_path = public as $$
begin
    if tg_op = 'DELETE' then
        perform registrar_log('usuarios', 'modelo', old.id, format('Excluiu o modelo de permissão "%s".', old.nome));
        return old;
    end if;

    new.nome := regexp_replace(trim(new.nome), '\s+', ' ', 'g');
    -- tira repetidas e põe em ordem, para comparar fácil
    new.permissoes := array(select distinct unnest(new.permissoes) order by 1);

    if tg_op = 'INSERT' then
        perform registrar_log('usuarios', 'modelo', new.id, format('Criou o modelo de permissão "%s".', new.nome));
    else
        new.atualizado_em := now();
        perform registrar_log('usuarios', 'modelo', new.id, format('Editou o modelo de permissão "%s".', new.nome));
    end if;
    return new;
end $$;

drop trigger if exists modelos_gatilho on modelos_permissao;
create trigger modelos_gatilho before insert or update or delete on modelos_permissao
    for each row execute function tg_modelos();

